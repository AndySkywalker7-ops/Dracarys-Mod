    private static void render(PoseStack stack, VertexConsumer consumer, int light, int overlay,
                               float[] vertices, int[] indices, float[] normals) {
        PoseStack.Pose pose = stack.last();
        Matrix4f matrix = pose.pose();
        Matrix3f normalMatrix = pose.normal();
        for (int tri = 0; tri < indices.length / 3; tri++) {
            float nx = normals[tri * 3];
            float ny = normals[tri * 3 + 1];
            float nz = normals[tri * 3 + 2];
            int i0 = indices[tri * 3];
            int i1 = indices[tri * 3 + 1];
            int i2 = indices[tri * 3 + 2];
            emit(consumer, matrix, normalMatrix, vertices, i0, nx, ny, nz, light, overlay);
            emit(consumer, matrix, normalMatrix, vertices, i1, nx, ny, nz, light, overlay);
            emit(consumer, matrix, normalMatrix, vertices, i2, nx, ny, nz, light, overlay);
            // Entity render types are quad-based; repeat the last point to form a degenerate quad.
            emit(consumer, matrix, normalMatrix, vertices, i2, nx, ny, nz, light, overlay);
        }
    }

    private static void emit(VertexConsumer c, Matrix4f matrix, Matrix3f normalMatrix,
                             float[] v, int index, float nx, float ny, float nz,
                             int light, int overlay) {
        int o = index * 5;
        c.vertex(matrix, v[o] * PX, v[o + 1] * PX, v[o + 2] * PX)
                .color(255, 255, 255, 255)
                .uv(v[o + 3], v[o + 4])
                .overlayCoords(overlay)
                .uv2(light)
                .normal(normalMatrix, nx, ny, nz)
                .endVertex();
    }
